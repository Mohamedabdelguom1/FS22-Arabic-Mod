"""
Merge the translation batches (key=Arabic, one per line) into the mod's
translations/l10n_ar.xml, checking each against the texts the game exported.

  python build_translations.py <l10n_source.xml> <batch files...> <out l10n_ar.xml>

A line is rejected when its key is not a game text or when its placeholders
(%s, %d, %.1f, $CURRENCY_SYMBOL...) differ from the English ones.
"""

import re
import sys
import xml.etree.ElementTree as ET

# no space flag: "100% damage" in plain English would read as "% d"
PLACEHOLDER = re.compile(r'%%|%[-+0#]*\d*(?:\.\d+)?[sdif]|\$[A-Z_]+')


def placeholders(text):
    return sorted(p for p in PLACEHOLDER.findall(text) if p != '%%') + \
        ['%%'] * text.count('%%')


def main():
    source, batches, out = sys.argv[1], sys.argv[2:-1], sys.argv[-1]
    english = {e.get('name'): e.get('text') for e in ET.parse(source).getroot().iter('text')}

    arabic, problems = {}, []
    for path in batches:
        for n, line in enumerate(open(path, encoding='utf-8'), 1):
            line = line.rstrip('\n')
            if not line.strip():
                continue
            key, sep, text = line.partition('=')
            where = '%s:%d %s' % (path.rsplit('\\', 1)[-1].rsplit('/', 1)[-1], n, key)
            if not sep or not text:
                problems.append(where + ': no text')
            elif key not in english:
                problems.append(where + ': not a game text')
            elif placeholders(text) != placeholders(english[key]):
                problems.append('%s: placeholders %s, English has %s'
                                % (where, placeholders(text), placeholders(english[key])))
            else:
                arabic[key] = text.replace('\\n', '\n')

    root = ET.Element('l10n')
    texts = ET.SubElement(root, 'texts')
    for key in sorted(arabic):
        ET.SubElement(texts, 'text', name=key, text=arabic[key])
    ET.indent(root, '    ')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('<?xml version="1.0" encoding="utf-8" standalone="no" ?>\n')
        f.write('<!-- Generated by arabic-font-tool/build_translations.py from FS22_ArabicLanguage_work/ar_*.txt -->\n')
        f.write(ET.tostring(root, encoding='unicode'))
        f.write('\n')

    print('%d texts written, %d of %d game texts translated (%.0f%%)'
          % (len(arabic), len(arabic), len(english), 100 * len(arabic) / len(english)))
    for p in problems:
        print('REJECTED', p)
    return 1 if problems else 0


if __name__ == '__main__':
    sys.exit(main())
